"""Write vetter/specs/powershell-params.toml: every parameter of the cmdlets
in specs/powershell.toml as Windows PowerShell 5.1 has them (switch or
taking a value, their aliases), asked of powershell.exe itself. The
resolver binds with them; the roles stay in powershell.toml.

    python -m tools.powershell.cmdlet_params [--powershell PATH]
"""

import argparse
import json
import pathlib
import subprocess
import sys
import tomllib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SPEC = ROOT / "vetter" / "specs" / "powershell.toml"
OUT = ROOT / "vetter" / "specs" / "powershell-params.toml"
POWERSHELL = "/mnt/c/Windows/System32/WindowsPowerShell/v1.0/powershell.exe"
COMMON = {"Verbose", "Debug", "ErrorAction", "WarningAction", "InformationAction", "ErrorVariable",
          "WarningVariable", "InformationVariable", "OutVariable", "OutBuffer", "PipelineVariable", "WhatIf",
          "Confirm"}

SCRIPT = r"""
$out = @{}
foreach ($n in $args[0].Split(',')) {
  $c = Get-Command $n -ErrorAction SilentlyContinue
  if (-not $c) { continue }
  $ps = @()
  foreach ($p in $c.Parameters.Values) {
    $ps += @{ name = $p.Name; switch = ($p.ParameterType -eq [switch]); aliases = @($p.Aliases) }
  }
  $out[$n] = $ps
}
$out | ConvertTo-Json -Depth 5 -Compress
"""


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--powershell", default=POWERSHELL)
    args = ap.parse_args(argv)
    names = [c["name"] for c in tomllib.load(open(SPEC, "rb"))["cmdlet"]]
    r = subprocess.run([args.powershell, "-NoProfile", "-NonInteractive", "-Command", SCRIPT.replace("$args[0]", repr(",".join(names)))],
                       capture_output=True, text=True, check=True)
    data = json.loads(r.stdout)
    lines = ["# Generated by tools/powershell/cmdlet_params.py from Windows PowerShell 5.1:",
             "# each cmdlet's parameters (common ones left out), `switch` or taking a",
             "# value, and their aliases. Don't edit: run the tool again.", ""]
    for n in names:
        if n not in data:
            print(f"(not on this system: {n})", file=sys.stderr)
            continue
        ps = data[n] if isinstance(data[n], list) else [data[n]]
        lines.append(f'[{json.dumps(n)}]')
        for p in sorted(ps, key=lambda p: p["name"]):
            if p["name"] in COMMON:
                continue
            al = [a for a in (p.get("aliases") or []) if a]
            lines.append(f'{p["name"]} = {{ switch = {str(bool(p["switch"])).lower()}, aliases = {json.dumps(al)} }}')
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(names)} cmdlets")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
